					Dropdown.Size = UDim2.new(1, 0, 0, DropdownData.Open and (45 + Count * 35) or 45)
					Arrow.Text = DropdownData.Open and "▲" or "▼"
				end

				for _, option in ipairs(options) do
					local Button = Instance.new("TextButton")

					Button.Parent = List
					Button.BackgroundColor3 = CurrentTheme.ElementBackground
					Button.BorderSizePixel = 0
					Button.Size = UDim2.new(1, 0, 0, 35)
					Button.Font = Enum.Font.SourceSans
					Button.Text = tostring(option)
					Button.TextColor3 = CurrentTheme.TextColor
					Button.TextScaled = true

					Button.MouseEnter:Connect(function()
						Button.BackgroundColor3 = CurrentTheme.ElementBackgroundHover
					end)

					Button.MouseLeave:Connect(function()
						Button.BackgroundColor3 = CurrentTheme.ElementBackground
					end)

					Button.MouseButton1Click:Connect(function()
						if MultiSelect then
							DropdownData.Values[option] = not DropdownData.Values[option]

							if DropdownData.Values[option] then
								Button.Text = tostring(option) .. " ✓"
							else
								Button.Text = tostring(option)
							end

							UpdateText()

							if callback then
								callback(DropdownData.Values)
							end
						else
							DropdownData.Value = option
							Text.Text = (text or "Dropdown") .. ": " .. tostring(option)

							DropdownData.Open = false
							RefreshSize()

							if callback then
								callback(option)
							end
						end
					end)
				end

				Arrow.MouseButton1Click:Connect(function()
					DropdownData.Open = not DropdownData.Open
					RefreshSize()
				end)

				function DropdownData:Set(value)
					if MultiSelect then
						DropdownData.Values[value] = true
						UpdateText()

						if callback then
							callback(DropdownData.Values)
						end
					else
						DropdownData.Value = value
						Text.Text = (text or "Dropdown") .. ": " .. tostring(value)

						if callback then
							callback(value)
						end
					end
				end

				function DropdownData:Get()
					if MultiSelect then
						return DropdownData.Values
					else
						return DropdownData.Value
					end
				end

				function DropdownData:Clear()
					DropdownData.Value = nil
					DropdownData.Values = {}
					Text.Text = text or "Dropdown"
				end

				function DropdownData:RefreshTheme()
					Dropdown.BackgroundColor3 = CurrentTheme.ElementBackground
					UIStroke.Color = CurrentTheme.ElementStroke
					Text.TextColor3 = CurrentTheme.TextColor
					Arrow.TextColor3 = CurrentTheme.TextColor
					List.BackgroundColor3 = CurrentTheme.Background
					ListStroke.Color = CurrentTheme.ElementStroke

					for _,v in ipairs(List:GetChildren()) do
						if v:IsA("TextButton") then
							v.BackgroundColor3 = CurrentTheme.ElementBackground
							v.TextColor3 = CurrentTheme.TextColor
						end
					end
				end

				RefreshSize()

				return DropdownData
			end

			function SectionData:ConfigToggle(text, default, callback, key)
				local cfgKey = key or text
				local value = CrackedLib.Config.Data[cfgKey] ~= nil and CrackedLib.Config.Data[cfgKey] or default

				local data = self:Toggle(text, value, function(state)
					CrackedLib.Config.Data[cfgKey] = state
					CrackedLib.Config:Save()
					if callback then callback(state) end
				end)
				return data
			end

			function SectionData:ConfigSlider(text, min, max, default, callback, key)
				local cfgKey = key or text
				local value = CrackedLib.Config.Data[cfgKey] ~= nil and CrackedLib.Config.Data[cfgKey] or default

				local data = self:Slider(text, min, max, value, function(val)
					CrackedLib.Config.Data[cfgKey] = val
					CrackedLib.Config:Save()
					if callback then callback(val) end
				end)
				return data
			end

			function SectionData:ConfigDropdown(text, options, callback, MultiSelect, key)
				local cfgKey = key or text
				local data = self:Dropdown(text, options, function(val)
					CrackedLib.Config.Data[cfgKey] = val
					CrackedLib.Config:Save()
					if callback then callback(val) end
				end, MultiSelect)
				return data
			end

			return SectionData
		end

		return TabData
	end

	if draggable then
		local UserInputService = game:GetService("UserInputService")
	
		local Dragging = false
		local DragStart, StartPos

		DropShadowHolder.InputBegan:Connect(function(input)
			if input.UserInputType == Enum.UserInputType.MouseButton1 
			or input.UserInputType == Enum.UserInputType.Touch then
				Dragging = true
				DragStart = input.Position
				StartPos = Main.Position
			end
		end)

		DropShadowHolder.InputEnded:Connect(function(input)
			if input.UserInputType == Enum.UserInputType.MouseButton1 
			or input.UserInputType == Enum.UserInputType.Touch then
				Dragging = false
			end
		end)

		UserInputService.InputChanged:Connect(function(input)
			if Dragging and (input.UserInputType == Enum.UserInputType.MouseMovement 
			or input.UserInputType == Enum.UserInputType.Touch) then
				local Delta = input.Position - DragStart
				Main.Position = UDim2.new(
					StartPos.X.Scale, StartPos.X.Offset + Delta.X,
					StartPos.Y.Scale, StartPos.Y.Offset + Delta.Y
				)
			end
		end)
	end

	if keybind then
		UserInputService.InputBegan:Connect(function(input, gameProcessed)
			if gameProcessed then return end
			if input.KeyCode == keybind then
				CrackLib.Enabled = not CrackLib.Enabled
			end
		end)
	end

	Exit.MouseButton1Click:Connect(function()
		CrackLib:Destroy()
	end)

	Minus.MouseButton1Click:Connect(function()
		Main.Visible = not Main.Visible
	end)

	return GUI
end

