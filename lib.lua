readfile = readfile or nil
isfile = isfile or nil

CrackedLib.Config = {
	FileName = "CrackedLib.json",
	Data = {}
}

local canSave = (writefile ~= nil and readfile ~= nil and isfile ~= nil)

function CrackedLib.Config:Save()
	if not canSave then return end
	pcall(function()
		writefile(self.FileName, game:GetService("HttpService"):JSONEncode(self.Data))
	end)
end

function CrackedLib.Config:Load()
	if not canSave then return end
	pcall(function()
		if isfile(self.FileName) then
			self.Data = game:GetService("HttpService"):JSONDecode(readfile(self.FileName))
		end
	end)
end

CrackedLib.Config:Load()


